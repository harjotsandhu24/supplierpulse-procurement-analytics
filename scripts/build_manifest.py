"""Write PUBLICATION_MANIFEST.md: every file intended for the public GitHub repository.

    python scripts/build_manifest.py

Files excluded by .gitignore (raw download, working database, virtual environment, caches)
are listed as excluded so a reviewer can see exactly what stays private.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXCLUDE_DIRS = {".venv", ".git", "__pycache__", ".pytest_cache", ".ruff_cache", "private"}
EXCLUDE_PREFIXES = ("data/raw/", "data/processed/")
EXCLUDE_SUFFIXES = (".egg-info",)


def is_excluded(rel: str) -> bool:
    parts = set(Path(rel).parts)
    return bool(parts & EXCLUDE_DIRS) or rel.startswith(EXCLUDE_PREFIXES) or any(p.endswith(EXCLUDE_SUFFIXES) for p in Path(rel).parts)


def main() -> None:
    included, excluded = [], []
    for p in sorted(ROOT.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(ROOT).as_posix()
        if rel == "PUBLICATION_MANIFEST.md":
            continue
        (excluded if is_excluded(rel) else included).append((rel, p.stat().st_size, p))
    total = sum(s for _, s, _ in included)
    lines = [
        "# Publication manifest",
        "",
        "Files prepared for the public repository `supplierpulse-procurement-analytics`. Generated by "
        "`python scripts/build_manifest.py`. **Nothing has been committed or pushed.**",
        "",
        f"- Files to publish: **{len(included)}** ({total / 1e6:,.1f} MB)",
        "- Largest file: the public City of Austin snapshot (address-free, redacted Parquet; redistribution permitted by the City's terms)",
        "- Excluded (git-ignored, stays local): `data/raw/` (original 98 MB download), `data/processed/` (DuckDB working database), `.venv/`, caches",
        "- Checks before publishing: `pytest` (includes e-mail/secret scan and size limits) and `python scripts/check_links.py`",
        "",
        "| File | Size (KB) | SHA-256 (first 12) |",
        "|---|---:|---|",
    ]
    for rel, size, p in included:
        digest = hashlib.sha256(p.read_bytes()).hexdigest()[:12]
        lines.append(f"| `{rel}` | {size / 1024:,.0f} | `{digest}` |")
    lines += ["", "## Excluded local files (not for publication)", ""]
    groups: dict[str, int] = {}
    for rel, _, _ in excluded:
        key = "/".join(Path(rel).parts[:2]) if rel.startswith("data/") else Path(rel).parts[0]
        groups[key] = groups.get(key, 0) + 1
    lines += [f"- `{k}`: {v} file(s)" for k, v in sorted(groups.items())]
    (ROOT / "PUBLICATION_MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(included)} files to publish ({total / 1e6:.1f} MB); {len(excluded)} excluded")


if __name__ == "__main__":
    main()
