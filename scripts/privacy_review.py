"""Scan every publishable file for private information and write docs/privacy_review.md.

    python scripts/privacy_review.py

Needs the private raw CSV (data/raw/) for the leakage layer; without it, only the pattern layer runs.
The report lists counts and file names only, never the private values themselves.
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from supplierpulse import privacy_scan  # noqa: E402
from supplierpulse.ingest import RAW_COLUMNS, SNAPSHOT_COLUMNS, read_raw  # noqa: E402


def main() -> int:
    files = privacy_scan.publishable_files()
    pat = privacy_scan.pattern_scan(files)
    raw_file = ROOT / "data" / "raw" / "austin_po_lines_raw.csv"
    leak = None
    needle_counts = {}
    if raw_file.exists():
        raw = read_raw(raw_file)
        reviewed = set(pd.read_csv(ROOT / "config" / "reviewed_vendor_names.csv", dtype=str)["vendor_name"])
        needles = privacy_scan.private_needles(raw, reviewed)
        needle_counts = {k: len(v) for k, v in needles.items()}
        leak = privacy_scan.leakage_scan(files, needles)
    snap = pd.read_parquet(ROOT / "data" / "public" / "austin_po_lines_snapshot.parquet")
    by_kind = Counter(k for _, k, _ in (leak.findings if leak else []))
    lines = [
        "# Privacy review of publishable files",
        "",
        "Generated by `python scripts/privacy_review.py`. Counts and file names only; private values are never written here.",
        "",
        "## Design",
        "",
        "- **Allowlist, not redaction.** The public snapshot keeps only these columns: " + ", ".join(f"`{c}`" for c in SNAPSHOT_COLUMNS) + ".",
        "- **Not published:** " + ", ".join(f"`{c}`" for c in RAW_COLUMNS if c not in {"PURCHASE_ORDER", "AWARD_DATE", "COMMODITY", "QUANTITY",
                                                                                         "UNIT_OF_MEASURE", "UNIT_PRICE", "ITM_TOT_AM", "DATA_BUILD_DATE", "CTRY"}) + ".",
        "- **Vendor names:** published only for the 170 business names on `config/reviewed_vendor_names.csv`; two vendors that appear to be "
        "individuals are withheld (`config/withheld_vendor_ids.csv`); all others appear as pseudonymous IDs.",
        "- **Item descriptions:** published only as reviewer-cleaned labels for the 153 product specifications on "
        "`config/reviewed_item_texts.csv`. Unreviewed text is not published, not even as a hash.",
        "",
        "## Results",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Publishable files | {len(files)} |",
        f"| Snapshot columns equal the allowlist | {'yes' if list(snap.columns) == SNAPSHOT_COLUMNS else 'NO'} ({len(snap):,} rows) |",
        f"| Files text-scanned for e-mail / phone patterns | {pat.files_scanned} |",
        f"| E-mail / phone pattern findings | {len(pat.findings)} |",
        f"| Image files (not text-scannable; rendered from scanned HTML) | {len(pat.unscannable)} |",
    ]
    if leak:
        lines += [
            f"| Private values searched for (from raw source) | " + ", ".join(f"{k}: {v:,}" for k, v in needle_counts.items()) + " |",
            f"| Files searched for private values | {leak.files_scanned} |",
            f"| Private values found in publishable files | {len(leak.findings)}" + (f" ({dict(by_kind)})" if leak.findings else "") + " |",
        ]
    else:
        lines.append("| Leakage scan against raw source | not run (raw file not present) |")
    if pat.findings or (leak and leak.findings):
        lines += ["", "## Findings (file and type only)", ""]
        lines += [f"- `{f}`: {k}" for f, k, _ in pat.findings]
        lines += [f"- `{f}`: {k}" for f, k, _ in (leak.findings if leak else [])]
    lines += ["", "Test fixtures use only fictional values (e.g. the reserved `example.gov` domain).", ""]
    (ROOT / "docs" / "privacy_review.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[12:]))
    if leak:
        for f, k, v in leak.findings[:40]:
            print("LOCAL ONLY:", f, k, v)
    return 1 if (pat.findings or (leak and leak.findings)) else 0


if __name__ == "__main__":
    sys.exit(main())
